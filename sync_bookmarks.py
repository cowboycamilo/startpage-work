#!/usr/bin/env python3
import json
import os
import platform

# Detect OS and set common Vivaldi paths
if platform.system() == 'Darwin':  # macOS
    BOOKMARKS_PATH = os.path.expanduser('~/Library/Application Support/Vivaldi/Default/Bookmarks')
else:  # Linux
    BOOKMARKS_PATH = os.path.expanduser('~/.config/vivaldi/Default/Bookmarks')

# Note: If your work Mac uses a specific Profile (not Default), 
# change 'Default' to 'Profile 1' or the folder name in the paths above.

OUTPUT_PATH = 'assets/js/all_links.js'

def extract_links(data):
    links = []
    if isinstance(data, dict):
        if 'type' in data and data['type'] == 'url':
            links.append({'name': data['name'], 'link': data['url']})
        if 'children' in data:
            for child in data['children']:
                links.extend(extract_links(child))
    return links

try:
    if not os.path.exists(BOOKMARKS_PATH):
        print(f"Error: Could not find Vivaldi bookmarks at {BOOKMARKS_PATH}")
        print("Tip: If you use a non-default profile, check ~/Library/Application Support/Vivaldi/ for the profile folder name.")
        exit(1)

    with open(BOOKMARKS_PATH, 'r') as f:
        data = json.load(f)
    
    all_bookmarks = []
    for root in data['roots'].values():
        all_bookmarks.extend(extract_links(root))

    with open(OUTPUT_PATH, 'w') as f:
        f.write('// Auto-generated by sync.sh\n')
        f.write('const ALL_LINKS = ' + json.dumps(all_bookmarks, indent=2) + ';')
    
    print(f"Success! Synced {len(all_bookmarks)} bookmarks to your start page.")

except Exception as e:
    print(f"An error occurred: {e}")
